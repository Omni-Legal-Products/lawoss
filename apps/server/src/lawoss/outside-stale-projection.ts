/**
 * LAWOSS: starý vygenerovaný `.opencode/opencode.json` v priečinku klienta outside (rozhodnutie MČ 9. 11. 2026).
 *
 * Skoršie buildy v2 zapísali projekciu nastavení aj do priečinka klienta outside. Engine ju teraz číta ako súbor, ktorý
 * napísal klient, takže by jeho lokáciám vrátila staré nastavenia popri `lawoss-outside-config`. Server ju preto pri
 * publikovaní nastavení (aj pri štarte) odstráni, ale len keď je to presne projekcia, ktorú vygeneroval: bajty sa
 * zhodujú so súkromným potvrdením projekcie, alebo súbor má hlavičku generátora, presne jeho formát a každý reťazec je
 * odkaz do súkromnej knižnice reťazcov servera. Súbor, ktorý napísal advokát (alebo ho zmenil), ostane. Pred
 * odstránením sa kópia uloží do app files klienta (mimo jeho priečinka).
 */
import { createHash } from "node:crypto";
import { lstat, mkdir, readFile, realpath, rm, rmdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { z } from "zod";
import { canonicalFilePath, withFileWriteLock } from "../file-write-lock.js";
import { readLegalworkWorkspaceConfig, writeLegalworkWorkspaceConfig } from "../legalwork-workspace-config-store.js";
import { runtimeStorageDir } from "../runtime-opencode-config-store.js";
import type { ServerConfig, WorkspaceInfo } from "../types.js";
import { externalAppFilesRoot, usesExternalWorkspaceAppFiles } from "./workspace-app-files.js";

/** Prvý riadok projekcie z `engine-project.ts` (`writeProjectProjection`). */
export const GENERATED_PROJECTION_HEADER = "// Generated by LegalWork. Definitions are kept in its private shared library.\n";
/** Kópie odstránených projekcií v app files klienta. */
export const RETIRED_PROJECTION_DIR = "retired-project-config";

const RECEIPT_KEY = "nativeEngineProject";
const NAMES = ["opencode.json", "opencode.jsonc"];
const receiptSchema = z.object({ projection: z.object({ path: z.string(), digest: z.string() }).optional() }).passthrough();
const digest = (value: Buffer | string) => createHash("sha256").update(value).digest("hex");
const missing = (error: unknown) => error instanceof Error && "code" in error && (error.code === "ENOENT" || error.code === "ENOTDIR");

/** Every string the generator writes is a sequence of `{file:…}`/`{env:…}` tokens, at least one into its private library. */
function generatedString(value: string, library: string): boolean {
  return /^(?:\s*\{(?:env|file):[^}]+\})+\s*$/.test(value) && value.includes(`{file:${library}/`)
    && [...value.matchAll(/\{file:([^}]+)\}/g)].every((match) => !match[1]!.startsWith(`${library}/`) || /^[0-9a-f]{64}\.txt$/.test(match[1]!.slice(library.length + 1)));
}

function leaves(value: unknown, library: string): { strings: number; foreign: boolean } {
  if (typeof value === "string") return { strings: 1, foreign: !generatedString(value, library) };
  if (Array.isArray(value) || (value && typeof value === "object")) {
    let strings = 0, foreign = false;
    for (const item of Array.isArray(value) ? value : Object.values(value)) {
      const inner = leaves(item, library);
      strings += inner.strings; foreign ||= inner.foreign;
    }
    return { strings, foreign };
  }
  return { strings: 0, foreign: false };
}

/** Exactly the generator's document: its header, its JSON formatting and only references into its private library. */
export function isGeneratedProjectionText(config: ServerConfig, text: string): boolean {
  if (!text.startsWith(GENERATED_PROJECTION_HEADER)) return false;
  let parsed: unknown;
  try { parsed = JSON.parse(text.slice(GENERATED_PROJECTION_HEADER.length)); } catch { return false; }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) return false;
  if (`${GENERATED_PROJECTION_HEADER}${JSON.stringify(parsed, null, 2)}\n` !== text) return false;
  const found = leaves(parsed, join(runtimeStorageDir(config), "native-config-strings"));
  return found.strings > 0 && !found.foreign;
}

/**
 * Removes a stale generated projection from an outside client's `.opencode` folder; returns the removed paths.
 * Only regular files (no symlink), only the generator's own bytes; the copy is written before removal and the file must
 * be unchanged between reading and removing. An empty `.opencode` folder left behind is removed too.
 */
export async function retireOutsideProjection(config: ServerConfig, workspace: WorkspaceInfo): Promise<string[]> {
  if (!usesExternalWorkspaceAppFiles(workspace)) return [];
  const directory = await canonicalFilePath(workspace.directory?.trim() || workspace.path).catch(() => null);
  if (!directory) return [];
  const folder = join(directory, ".opencode");
  const parent = await lstat(folder).catch((error) => { if (missing(error)) return null; throw error; });
  if (!parent?.isDirectory() || parent.isSymbolicLink()) return [];
  const receipt = receiptSchema.safeParse((await readLegalworkWorkspaceConfig(config, workspace.id))[RECEIPT_KEY]);
  const projection = receipt.success ? receipt.data.projection : undefined;
  const removed: string[] = [];
  for (const name of NAMES) {
    const path = join(folder, name);
    await withFileWriteLock(path, async () => {
      const before = await lstat(path).catch((error) => { if (missing(error)) return null; throw error; });
      if (!before?.isFile() || before.isSymbolicLink() || await realpath(path) !== path) return;
      const content = await readFile(path);
      const owned = projection?.path === path && digest(content) === projection.digest;
      if (!owned && !isGeneratedProjectionText(config, content.toString("utf8"))) return;
      const copies = join(externalAppFilesRoot(config, workspace), RETIRED_PROJECTION_DIR);
      await mkdir(copies, { recursive: true, mode: 0o700 });
      const copy = join(copies, `${digest(content)}-${name}`);
      await writeFile(copy, content, { flag: "wx", mode: 0o600 }).catch(async (error) => {
        if (!(error instanceof Error && "code" in error && error.code === "EEXIST")) throw error;
        if (!(await readFile(copy)).equals(content)) throw new Error("The saved copy of the generated client settings was changed.");
      });
      const after = await lstat(path);
      if (!after.isFile() || after.isSymbolicLink() || after.ino !== before.ino || after.mtimeMs !== before.mtimeMs || !(await readFile(path)).equals(content)) return;
      await rm(path);
      removed.push(path);
      if (projection?.path === path) await writeLegalworkWorkspaceConfig(config, workspace.id, (current) => {
        const record = receiptSchema.safeParse(current[RECEIPT_KEY]);
        if (!record.success || record.data.projection?.path !== path) return current;
        const { projection: _retired, ...rest } = record.data;
        return { ...current, [RECEIPT_KEY]: rest };
      });
    });
  }
  if (removed.length) await rmdir(folder).catch(() => undefined);
  return removed;
}
