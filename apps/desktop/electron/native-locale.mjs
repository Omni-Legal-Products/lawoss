export function normalizeUiLocale(value) {
  if (typeof value !== "string") return null;
  const language = value.toLowerCase().split("-")[0];
  return Object.hasOwn(NATIVE_STRINGS, language) ? language : null;
}
/**
 * Jazyk natívneho menu pred prvým hlásením renderera, rovnakým pravidlom ako voľba „Systém“ v appke
 * (apps/app/src/lawoss/i18n/system-language.ts, N-2 22. 10. 2026): SK/CS kdekoľvek v zozname systému,
 * inak prvý podporovaný jazyk, inak slovenčina.
 */
export function preferredSystemLocale(languages) {
  const supported = (Array.isArray(languages) ? languages : []).map(normalizeUiLocale).filter(Boolean);
  return supported.find(language => language === "sk" || language === "cs") ?? supported[0] ?? "sk";
}
export function nativeCopy(locale = "en", app = "LAWOSS") {
  const strings = NATIVE_STRINGS[normalizeUiLocale(locale) ?? "en"];
  return Object.fromEntries(Object.entries(strings).map(([key, value]) => [key, value.replaceAll("{app}", app)]));
}
/** Presentation mirrors resolved renderer state; it never changes policy or approval decisions. */
export function createNativeLocaleState(fallback = () => "en") {
  const windows = new WeakMap();
  const listeners = new Set();
  return {
    forWindow: window => (window && windows.get(window)) ?? normalizeUiLocale(fallback()) ?? "en",
    setForWindow(window, locale) {
      if (!window || !Object.hasOwn(NATIVE_STRINGS, locale)) return false;
      if (windows.get(window) === locale) return true;
      windows.set(window, locale);
      for (const listener of listeners) listener(window, locale);
      return true;
    },
    subscribe(listener) { listeners.add(listener); return () => listeners.delete(listener); },
  };
}

/** Admit presentation reports only from an ordinary owning application main frame. */
export function acceptUiLocaleReport(event, locale, { fromWebContents, isAppWindow, isAppUrl, state }) {
  const owner = fromWebContents(event?.sender);
  if (!owner || !isAppWindow(owner) || owner.isDestroyed() || event?.senderFrame !== event?.sender?.mainFrame
      || !isAppUrl(event.senderFrame?.url) || typeof locale !== "string" || !Object.hasOwn(NATIVE_STRINGS, locale)) return false;
  return state.setForWindow(owner, locale);
}
